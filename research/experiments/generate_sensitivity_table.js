// Emits the paper's sensitivity table (LaTeX rows) directly from sensitivity-bare-keyword-results.json
// so no number in it is hand-typed. Output is \input by research/paper/acl_latex/content.tex.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..', '..');
const res = JSON.parse(fs.readFileSync(path.join(root, 'research/results/stats/sensitivity-bare-keyword-results.json'), 'utf-8'));
const by = Object.fromEntries(res.versions.map(v => [v.benchmark, v.subsets]));

const rows = [
  ['v0.1', 'all queries', by['v0.1'].ALL],
  ['v0.1', 'w/o 9 bare-keyword', by['v0.1'].DROP_ALL_BK],
  ['v0.2', 'all queries', by['v0.2'].ALL],
  ['v0.2', 'w/o 17 new bare-keyword', by['v0.2'].DROP_NEW_BK],
  ['v0.2', 'w/o all 26 bare-keyword', by['v0.2'].DROP_ALL_BK],
  ['both', 'answerable only', by['v0.2'].ANSWERABLE]
];
const p = x => (x < 0.001 ? x.toExponential(0) : x.toFixed(3));
const sgn = x => (x >= 0 ? '+' : '$-$') + Math.abs(x).toFixed(1);
// The answerable-only accuracy columns are identical for v0.1 and v0.2 (asserted below), but the
// calibration pool also contains the OOD queries, which differ (15 vs 50), so the ECE cell shows both.
const eceCell = (bm, r) => bm === 'both'
  ? `${by['v0.1'].ANSWERABLE.calibration.relative_reduction_pct.toFixed(0)}/${by['v0.2'].ANSWERABLE.calibration.relative_reduction_pct.toFixed(0)}\\%`
  : `${r.calibration.relative_reduction_pct.toFixed(0)}\\%`;
const lines = rows.map(([bm, sub, r]) =>
  `    ${bm === 'both' ? 'v0.1/v0.2' : bm} & ${sub} & ${r.n_nonOOD_evaluated} & ${sgn(r.A0_vs_A3.delta_pp)} (${p(r.A0_vs_A3.exact_mcnemar_p)}) & ${sgn(r.A2_vs_A3.delta_pp)} (${p(r.A2_vs_A3.exact_mcnemar_p)}) & ${eceCell(bm, r)} \\\\`);

// v0.1 and v0.2 "answerable only" subsets must be the identical query set; assert it so the "both" row is honest.
const a1 = by['v0.1'].ANSWERABLE, a2 = by['v0.2'].ANSWERABLE;
if (a1.n_nonOOD_evaluated !== a2.n_nonOOD_evaluated || a1.A0_vs_A3.exact_mcnemar_p !== a2.A0_vs_A3.exact_mcnemar_p || a1.A2_vs_A3.exact_mcnemar_p !== a2.A2_vs_A3.exact_mcnemar_p) {
  console.error('ABORT: answerable-only subsets differ between v0.1 and v0.2; "both" row would be wrong.'); process.exit(1);
}

const tex = `% AUTO-GENERATED by research/experiments/generate_sensitivity_table.js -- do not edit by hand.
\\begin{tabular}{@{}llrccr@{}}
    \\toprule
    \\textbf{Ver.} & \\textbf{Evaluated on} & \\textbf{n} & \\textbf{BM25$\\to$Hyb.} & \\textbf{Dense$\\to$Hyb.} & \\textbf{ECE red.} \\\\
    \\midrule
${lines.join('\n')}
    \\bottomrule
  \\end{tabular}
`;
fs.writeFileSync(path.join(root, 'research/paper/acl_latex/table_sensitivity.tex'), tex, 'utf-8');
console.log(tex);
